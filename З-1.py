# 2 Задание. Проверка длины пароля с помощью цикла while
password = input("Введите пароль: ")

while len(password) < 8:
    print("Пароль слишком короткий! Длина должна быть не менее 8 символов.")
    password = input("Введите пароль: ")

print("Пароль принят!")

